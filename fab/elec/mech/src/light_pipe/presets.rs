//! Named light pipe parameter sets.

use super::params::{param_table, PipeParams};

/// A light pipe's name and parameter text.
pub struct Preset {
    pub name: &'static str,
    pub text: &'static str,
}

/// The available light pipe parameter sets.
pub fn presets() -> &'static [Preset] {
    PRESETS
}

/// Load a named preset over the default parameters.
pub fn preset(name: &str) -> Option<PipeParams> {
    let entry = presets().iter().find(|entry| entry.name == name)?;
    let mut params = PipeParams::default();
    param_table().from_text(entry.text, &mut params, None).ok()?;
    Some(params)
}

