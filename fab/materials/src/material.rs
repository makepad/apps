/// By id, short name or full name; see [`MaterialId::lookup`].
pub(crate) fn lookup(name: &str) -> Option<MaterialId> {
    fn key(name: &str) -> String {
        name.to_ascii_lowercase().replace('_', "-")
    }
    let name = key(name);
    let name = match name.as_str() {
        "pmma-clear" => "pmma",
        "pc-clear" => "pc",
        name => name,
    };
    MATERIALS
        .iter()
        .position(|m| name == key(m.id) || name == key(m.short_name) || name == key(m.full_name))
        .map(|index| MaterialId(index as u16))
}

const DARK_L: f32 = 35.0;
const DARK_C: f32 = 8.0;

impl Material {
    /// Grams for a solid volume in cubic millimetres.
    pub fn mass_grams(&self, volume_mm3: f64) -> f32 {
        (volume_mm3 * 1e-3 * self.density as f64) as f32
    }

    /// Allowable snap-fit strain in percent; repeated assembly uses 60 %.
    pub fn snap_strain_limit(&self, repeated: bool) -> f32 {
        if repeated { 0.6 * self.snap_strain } else { self.snap_strain }
    }

    /// Draft per side on a polished or lightly textured face, in degrees.
    pub fn recommended_draft(&self, textured: bool) -> f32 {
        if textured { self.draft_textured } else { self.draft_polished }
    }

    pub fn is_conductive(&self) -> bool {
        matches!(self.electrical.class, ElectricalClass::Conductive | ElectricalClass::EmiShielding)
    }

    pub fn is_static_dissipative(&self) -> bool {
        self.electrical.class != ElectricalClass::Insulating
    }

    /// Carbon-filled grades allow only black through dark grey.
    pub fn colour_allowed(&self, srgb: Srgb) -> bool {
        if !self.electrical.dark_only {
            return true;
        }
        let [l, a, b] = fab_colour::lab::srgb_to_lab(srgb);
        l <= DARK_L + 0.01 && a.hypot(b) <= DARK_C + 0.01
    }

    pub fn translucency_allowed(&self) -> bool {
        self.can_translucent && !self.electrical.dark_only
    }

    /// Darken and desaturate a colour to fit the material's palette.
    pub fn clamp_colour(&self, srgb: Srgb) -> Srgb {
        if self.colour_allowed(srgb) {
            return srgb;
        }
        // Desaturate toward equal luminance grey, then scale down until L* fits.
        let y = 0.2126 * srgb[0] + 0.7152 * srgb[1] + 0.0722 * srgb[2];
        let mut out = srgb;
        for _ in 0..40 {
            if self.colour_allowed(out) {
                break;
            }
            out = out.map(|v| 0.5 * (v + y));
            if fab_colour::lab::srgb_to_lab(out)[0] > DARK_L {
                out = out.map(|v| v * 0.9);
            }
        }
        if self.colour_allowed(out) { out } else { [0.11, 0.11, 0.12] }
    }

    /// A short multiline tooltip of the material's properties and design rules.
    pub fn summary(&self) -> String {
        if !self.family.is_moulding() {
            let mut optics = if let Some([r, g, b]) = self.f0 {
                format!("metal, f0 {r:.3} {g:.3} {b:.3}")
            } else {
                format!("ior {}, translucency {}", three_significant(self.optics.ior), three_significant(self.translucency))
            };
            if self.family == Family::Coating {
                optics.push_str(&format!("; coat {}-{} um", three_significant(self.coat_um.lo), three_significant(self.coat_um.hi)));
            }
            return format!(
                "{} - {} ({})\n{} g/cm3\n{}\n{}",
                self.short_name, self.full_name, self.family.name(),
                three_significant(self.density), optics, self.notes,
            );
        }
        let hdt = match self.hdt_load {
            HdtLoad::None => "HDT n/a".to_owned(),
            HdtLoad::MPa045 => format!("HDT {:.0} C @0.45 MPa", self.hdt),
            HdtLoad::MPa18 => format!("HDT {:.0} C @1.8 MPa", self.hdt),
        };
        let ri = if self.optics.ior > 0.0 { format!(", n {:.3}", self.optics.ior) } else { String::new() };
        let sci = |v: f32| format!("1e{}", v.max(1e-30).log10().round() as i32);
        format!(
            "{} - {} ({})\n\
             {} g/cm3, {}{}; {}\n\
             E {} GPa, {:.0} MPa, {}, max {:.0} C\n\
             Wall {:.1}-{:.1} mm (min {:.2}), draft {:.1} / {:.1} deg, snap {:.1} %\n\
             Shrink {:.1}-{:.1} %, {} {}-{} ohm cm\n\
             {}",
            self.short_name, self.full_name, self.family.name(),
            three_significant(self.density), self.optics.clarity.name(), ri, self.processes.names(),
            three_significant(self.modulus), self.tensile_strength, hdt, self.max_service_temp,
            self.wall.lo, self.wall.hi, self.min_wall, self.draft_polished, self.draft_textured, self.snap_strain,
            self.shrinkage.lo, self.shrinkage.hi, self.electrical.class.name(),
            sci(self.electrical.volume_resistivity.lo), sci(self.electrical.volume_resistivity.hi), self.notes,
        )
    }
}

// Three significant digits, with the general-format exponent and trailing-zero rules.
pub(crate) fn three_significant(value: f32) -> String {
    let scientific = format!("{value:.2e}");
    let Some((mantissa, exponent)) = scientific.split_once('e') else {
        return scientific;
    };
    let exponent: i32 = exponent.parse().expect("formatted decimal exponent");
    if (-4..3).contains(&exponent) {
        let precision = (2 - exponent) as usize;
        let decimal = format!("{value:.precision$}");
        if precision == 0 { decimal } else { decimal.trim_end_matches('0').trim_end_matches('.').to_owned() }
    } else {
        format!("{}e{exponent:+03}", mantissa.trim_end_matches('0').trim_end_matches('.'))
    }
}

