    #[test]
    fn machining_metals() {
        // f0 is the linear decode of the sRGB natural colour, dimmed by the coating's metalness.
        for (id, metalness) in [
            ("brass", 1.0), ("nickel_brass", 1.0), ("bronze", 1.0), ("copper", 1.0),
            ("aluminium_anodised", 0.85), ("stainless_303", 1.0), ("steel_black_oxide", 0.6),
        ] {
            let m = MaterialId::lookup(id).expect("machining metal resolves by id").get();
            assert_eq!(m.family, Family::Metal, "machining metal family: {id}");
            assert_eq!(m.processes, Processes::CNC, "machining metal process: {id}");
            let f0 = m.f0.expect("machining metal has f0");
            for channel in 0..3 {
                let expected = fab_colour::oklab::to_linear(m.natural[channel]) * metalness;
                assert!((f0[channel] - expected).abs() < 1e-6,
                    "f0 decodes reflectance and scales metalness: {id}, channel {channel}");
            }
            assert_eq!(m.electrical.class, ElectricalClass::Conductive, "machining metal is conductive: {id}");
            assert!(m.modulus > 0.0 && m.tensile_strength > 0.0, "machining metal mechanics are supplied: {id}");
            assert!(!m.family.is_moulding(), "machining metals stay out of moulding pickers: {id}");
        }
    }

